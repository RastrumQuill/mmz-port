#!/usr/bin/env python3
"""Merge the label rows the renderer writes (MMZ_LABELS_TSV=path, one block per area / flag key it labels)
into docs/wideview-labels.tsv: ids and names only (area, flag key, chunk, layer bits, set pair, how the label
was made, the layers' BG / priority / char block / backdrop). No ROM bytes.

  MMZ_LABELS_TSV=/tmp/l.tsv python3 port/tools/motioncheck.py ...   # or any mmz run
  python3 port/tools/labels_tsv.py /tmp/l.tsv [more.tsv ...] > docs/wideview-labels.tsv
"""
import sys
HEAD = "area\tdesc:flag_key\tcx\tcy\tlayers\tpair\thow\tlayer_config"
rows = set()
for p in sys.argv[1:]:
    for line in open(p):
        f = line.rstrip("\n").split("\t")
        if len(f) >= 7: rows.add((int(f[0]), f[1], int(f[2]), int(f[3]), f[4], f[5], f[6], " ".join(f[7:])))
print("# generated by port/tools/labels_tsv.py from the renderer's label table (view.c labels_build); do not edit")
print("# layers: bit k = stage layer k; pair: graphics set pair (hi lo); how: own | neighbour (taken from the nearest")
print("# labelled chunk in the row/column) | empty; layer_config: L<k>:bg<n>:p<prio>:c<char block>:s<backdrop>")
print(HEAD)
for r in sorted(rows): print("\t".join(str(x) for x in r))
